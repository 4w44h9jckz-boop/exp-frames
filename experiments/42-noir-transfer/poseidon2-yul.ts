// Writes Poseidon2.yul: Barretenberg's Poseidon2 permutation over BN254 (t = 4, 8 full rounds,
// 56 partial rounds, x^5), unrolled, with the constants read from vendor/poseidon2_params.hpp,
// behind the sponge transfer.nr hashes with.
//
// usage: npx tsx experiments/42-noir-transfer/poseidon2-yul.ts
import { readFileSync, writeFileSync } from 'node:fs'

const here = (f: string) => new URL(f, import.meta.url)
const params = readFileSync(here('./vendor/poseidon2_params.hpp'), 'utf8')
const block = (name: string) => {
  const start = params.indexOf(name)
  const end = params.indexOf('};', start)
  return [...params.slice(start, end).matchAll(/"(0x[0-9a-f]{64})"/g)].map((m) => m[1])
}
const diag = block('internal_matrix_diagonal_minus_one =')
const rc = block('round_constants{')
if (diag.length !== 4 || rc.length !== 64 * 4) throw new Error('unexpected parameter file')
const c = (r: number, i: number) => rc[4 * r + i]

const lines: string[] = []
const full = (r: number) => {
  lines.push(`                // full round ${r}`)
  for (let i = 0; i < 4; i++) lines.push(`                s${i} := sbox(addmod(s${i}, ${c(r, i)}, p))`)
  lines.push('                s0, s1, s2, s3 := external(s0, s1, s2, s3)')
}
const partial = (r: number) => {
  for (let i = 1; i < 4; i++) if (BigInt(c(r, i)) !== 0n) throw new Error(`partial round ${r} has a constant off s0`)
  lines.push(`                s0 := sbox(addmod(s0, ${c(r, 0)}, p))`)
  lines.push('                s0, s1, s2, s3 := internal(s0, s1, s2, s3)')
}
for (let r = 0; r < 4; r++) full(r)
for (let r = 4; r < 60; r++) partial(r)
for (let r = 60; r < 64; r++) full(r)

const yul = `// Poseidon2 over BN254 as Barretenberg and Noir's std::hash::poseidon2_permutation compute it,
// behind the sponge experiment 42's circuit hashes with:
//
//   state = [0, 0, 0, N * 2^64]; for each chunk of three inputs, add it to state[0..3] and permute;
//   the hash is state[0].
//
// calldata = N words, each below the field modulus; returns the hash. N = 0 is refused.
// Generated by poseidon2-yul.ts from vendor/poseidon2_params.hpp (Barretenberg, Apache-2.0);
// do not edit by hand.
object "Poseidon2" {
    code {
        datacopy(0, dataoffset("runtime"), datasize("runtime"))
        return(0, datasize("runtime"))
    }
    object "runtime" {
        code {
            let count := shr(5, calldatasize())
            if or(iszero(count), mod(calldatasize(), 32)) { revert(0, 0) }
            let h0 := 0
            let h1 := 0
            let h2 := 0
            let h3 := shl(64, count)
            for { let i := 0 } lt(i, count) { i := add(i, 3) } {
                h0 := addmod(h0, input(i, count), P())
                h1 := addmod(h1, input(add(i, 1), count), P())
                h2 := addmod(h2, input(add(i, 2), count), P())
                h0, h1, h2, h3 := permute(h0, h1, h2, h3)
            }
            mstore(0, h0)
            return(0, 32)

            function P() -> p { p := 0x30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001 }

            function input(i, len) -> v {
                if lt(i, len) {
                    v := calldataload(shl(5, i))
                    if iszero(lt(v, P())) { revert(0, 0) }
                }
            }

            function sbox(x) -> y {
                let p := P()
                let x2 := mulmod(x, x, p)
                y := mulmod(mulmod(x2, x2, p), x, p)
            }

            // The MDS matrix [[5,7,1,3],[4,6,1,1],[1,3,5,7],[1,1,4,6]], in the Poseidon2 paper's order.
            function external(a, b, c, d) -> o0, o1, o2, o3 {
                let p := P()
                let t0 := addmod(a, b, p)
                let t1 := addmod(c, d, p)
                let t2 := addmod(addmod(b, b, p), t1, p)
                let t3 := addmod(addmod(d, d, p), t0, p)
                let t4 := addmod(mulmod(t1, 4, p), t3, p)
                let t5 := addmod(mulmod(t0, 4, p), t2, p)
                o0 := addmod(t3, t5, p)
                o1 := t5
                o2 := addmod(t2, t4, p)
                o3 := t4
            }

            // x_i -> (D_i - 1) x_i + sum(x).
            function internal(a, b, c, d) -> o0, o1, o2, o3 {
                let p := P()
                let sum := addmod(addmod(a, b, p), addmod(c, d, p), p)
                o0 := addmod(mulmod(a, ${diag[0]}, p), sum, p)
                o1 := addmod(mulmod(b, ${diag[1]}, p), sum, p)
                o2 := addmod(mulmod(c, ${diag[2]}, p), sum, p)
                o3 := addmod(mulmod(d, ${diag[3]}, p), sum, p)
            }

            function permute(a, b, c, d) -> s0, s1, s2, s3 {
                let p := P()
                s0, s1, s2, s3 := external(a, b, c, d)
${lines.join('\n')}
            }
        }
    }
}
`
writeFileSync(here('./Poseidon2.yul'), yul)
