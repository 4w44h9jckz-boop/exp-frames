// Experiment 35: how many notes would satisfy a statement before a wallet proves it, from mainnet
// data alone. Read-only, as experiment 30's mainnet.ts is.
//
//   1. "I deposited into this pool before date D": Tornado Cash's four ETH pools. The count is
//      the pool's nextIndex() at the last block before D.
//   2. "I hold an unspent note worth at least T": the same pools. An ETH pool holds exactly its
//      denomination per unspent note, so the count is the sum of balance / denomination over
//      the pools whose denomination is at least T.
//   3. "My deposit is in the association set": Privacy Pools' ETH pool. The count is the number
//      of labels in the latest set the association-set provider published on chain, as a root
//      and the IPFS CID of the whole tree. The tree is fetched, every level recomputed with
//      Poseidon, and its root checked against the chain's.
//
// Each count is checked once by hand: the deposits on either side of D's boundary; the identity
// of statement 2 across one day of deposits and withdrawals; and one label of the set traced
// to its deposit.
//
// Addresses as experiment 30 read them: tornadocash/tornado-cli config.js (netId 1), and
// docs.privacypools.com/deployments. Events: tornado-core Tornado.sol, privacy-pools-core
// IEntrypoint.sol and IPrivacyPool.sol.
//
// usage: npx tsx experiments/35-disclosure-counts/counts.ts [snapshot block]
//   The snapshot defaults to the latest finalized block. MAINNET_RPC_URL overrides the RPC and
//   IPFS_GATEWAY the gateway. The output is results.md.
import { writeFileSync } from 'node:fs'
import { buildPoseidon } from 'circomlibjs'
import { type Address, createPublicClient, formatEther, http, parseAbi, parseAbiItem } from 'viem'
import { mainnet } from 'viem/chains'

const RPC = process.env.MAINNET_RPC_URL ?? 'https://mainnet.gateway.tenderly.co'
const GATEWAY = process.env.IPFS_GATEWAY ?? 'https://gateway.pinata.cloud/ipfs/'
const client = createPublicClient({ chain: mainnet, transport: http(RPC, { retryCount: 6, retryDelay: 1_000, timeout: 60_000 }) })

const TORNADO: { denomination: bigint; label: string; address: Address }[] = [
  { label: '0.1 ETH', denomination: 10n ** 17n, address: '0x12D66f87A04A9E220743712cE6d9bB1B5616B8Fc' },
  { label: '1 ETH', denomination: 10n ** 18n, address: '0x47CE0C6eD5B0Ce3d3A51fdb1C52DC66a7c3c2936' },
  { label: '10 ETH', denomination: 10n ** 19n, address: '0x910Cbd523D972eb0a6f4cAe4618aD62622b39DbF' },
  { label: '100 ETH', denomination: 10n ** 20n, address: '0xA160cdAB225685dA1d56aa342Ad8841c3b53f291' },
]
const PP_ENTRYPOINT: Address = '0x6818809eefce719e480a7526d76bd3e561526b46'
const PP_ETH_POOL: Address = '0xf241d57c6debae225c0f2e6ea1529373c9a9c9fb'

const tornadoAbi = parseAbi(['function nextIndex() view returns (uint32)'])
const tornadoDeposit = parseAbiItem('event Deposit(bytes32 indexed commitment, uint32 leafIndex, uint256 timestamp)')
const tornadoWithdrawal = parseAbiItem('event Withdrawal(address to, bytes32 nullifierHash, address indexed relayer, uint256 fee)')
const rootUpdated = parseAbiItem('event RootUpdated(uint256 _root, string _ipfsCID, uint256 _timestamp)')
const ppDeposited = parseAbiItem('event Deposited(address indexed _depositor, uint256 _commitment, uint256 _label, uint256 _value, uint256 _precommitmentHash)')

const out: string[] = []
const say = (s = '') => {
  console.log(s)
  out.push(s)
}
const iso = (t: bigint) => new Date(Number(t) * 1000).toISOString().replace('.000Z', 'Z')

const finalized = (await client.getBlock({ blockTag: 'finalized' })).number
const snapshot = process.argv[2] ? BigInt(process.argv[2]) : finalized
const snapshotTime = (await client.getBlock({ blockNumber: snapshot })).timestamp

/** The last block whose timestamp is before `t`. */
async function blockBefore(t: bigint): Promise<bigint> {
  let lo = 1n
  let hi = snapshot
  while (lo < hi) {
    const mid = (lo + hi + 1n) / 2n
    if ((await client.getBlock({ blockNumber: mid })).timestamp < t) lo = mid
    else hi = mid - 1n
  }
  return lo
}

const nextIndex = (pool: Address, blockNumber: bigint) => client.readContract({ address: pool, abi: tornadoAbi, functionName: 'nextIndex', blockNumber })

/** Logs over a block range in chunks the RPC accepts. */
async function logsOf<E extends typeof tornadoDeposit | typeof tornadoWithdrawal | typeof rootUpdated | typeof ppDeposited>(address: Address, event: E, from: bigint, to: bigint, step = 50_000n) {
  const all = []
  for (let a = from; a <= to; a += step) {
    const b = a + step - 1n < to ? a + step - 1n : to
    all.push(...(await client.getLogs({ address, event, fromBlock: a, toBlock: b })))
  }
  return all
}

say('# Experiment 35: disclosure counts, from mainnet data')
say()
say(`Generated by \`npx tsx experiments/35-disclosure-counts/counts.ts ${snapshot}\`: do not edit; run it again and compare.`)
say(`Snapshot: block ${snapshot} (${iso(snapshotTime)}). RPC: ${RPC}. IPFS gateway: ${GATEWAY}.`)

// ---- 1. a deposit before a date ----

say()
say('## 1. "I deposited into this pool before date D"')
say()
say('| D | Block before D | ' + TORNADO.map((p) => `Tornado ${p.label}`).join(' | ') + ' |')
say('|---|---|' + TORNADO.map(() => '---|').join(''))
const DATES = ['2021-01-01', '2023-01-01', '2025-01-01', '2026-01-01']
const boundary: Record<string, bigint> = {}
for (const d of DATES) {
  const t = BigInt(Date.parse(`${d}T00:00:00Z`) / 1000)
  const b = await blockBefore(t)
  boundary[d] = b
  const counts = await Promise.all(TORNADO.map((p) => nextIndex(p.address, b)))
  say(`| ${d} | ${b} | ${counts.map((c) => c.toLocaleString('en-US')).join(' | ')} |`)
}

// Checked by hand: the 1 ETH pool across 2025-01-01. The deposit numbered count - 1 is before
// D, the one numbered count is not.
{
  const pool = TORNADO[1]
  const b = boundary['2025-01-01']
  const count = await nextIndex(pool.address, b)
  const around = await logsOf(pool.address, tornadoDeposit, b - 20_000n, b + 20_000n, 10_000n)
  const last = around.find((l) => l.args.leafIndex === count - 1)
  const first = around.find((l) => l.args.leafIndex === count)
  say()
  say(`Checked by hand, Tornado 1 ETH across 2025-01-01: nextIndex() at block ${b} is ${count}.`)
  if (last) say(`- deposit ${count - 1}: block ${last.blockNumber}, ${iso(last.args.timestamp!)}, tx ${last.transactionHash}`)
  if (first) say(`- deposit ${count}: block ${first.blockNumber}, ${iso(first.args.timestamp!)}, tx ${first.transactionHash}`)
  if (!last || !first || last.args.timestamp! >= BigInt(Date.parse('2025-01-01T00:00:00Z') / 1000) || first.args.timestamp! < BigInt(Date.parse('2025-01-01T00:00:00Z') / 1000)) {
    throw new Error('the boundary check failed')
  }
}

// ---- 2. an unspent note worth at least T ----

say()
say('## 2. "I hold an unspent note worth at least T"')
say()
const held = await Promise.all(
  TORNADO.map(async (p) => {
    const balance = await client.getBalance({ address: p.address, blockNumber: snapshot })
    return { ...p, balance, unspent: balance / p.denomination, dust: balance % p.denomination, deposits: await nextIndex(p.address, snapshot) }
  }),
)
say('| Pool | Balance | Unspent notes (balance / denomination) | Remainder | Deposits ever |')
say('|---|---|---|---|---|')
for (const h of held) say(`| Tornado ${h.label} | ${formatEther(h.balance)} ETH | ${h.unspent.toLocaleString('en-US')} | ${h.dust} wei | ${h.deposits.toLocaleString('en-US')} |`)
say()
say('| T | Notes worth at least T |')
say('|---|---|')
for (const t of TORNADO) {
  const n = held.filter((h) => h.denomination >= t.denomination).reduce((s, h) => s + h.unspent, 0n)
  say(`| ${t.label} | ${n.toLocaleString('en-US')} |`)
}

// Checked by hand: across the last 7,200 blocks, for the 10 ETH pool, the change in unspent
// notes is the deposits made minus the withdrawals logged.
{
  const p = TORNADO[2]
  const from = snapshot - 7_200n
  const [i0, i1, b0] = await Promise.all([nextIndex(p.address, from), nextIndex(p.address, snapshot), client.getBalance({ address: p.address, blockNumber: from })])
  const withdrawals = (await logsOf(p.address, tornadoWithdrawal, from + 1n, snapshot)).length
  const u0 = b0 / p.denomination
  const u1 = held[2].unspent
  say()
  say(`Checked by hand, Tornado 10 ETH from block ${from} to ${snapshot}: ${i1 - i0} deposits and ${withdrawals} withdrawals; unspent notes went from ${u0} to ${u1}.`)
  if (u1 - u0 !== BigInt(i1 - i0) - BigInt(withdrawals)) throw new Error('the unspent-note identity failed')
  say(`${u1} - ${u0} = ${i1 - i0} - ${withdrawals}: the identity holds.`)
}

// ---- 3. membership of the association set ----

say()
say('## 3. "My deposit is in the association set"')
say()
const roots = await logsOf(PP_ENTRYPOINT, rootUpdated, snapshot - 20_000n, snapshot, 10_000n)
const latest = roots.at(-1)
if (!latest) throw new Error('no association-set root in the last 20,000 blocks')
const cid = latest.args._ipfsCID!
const root = latest.args._root!
const res = await fetch(`${GATEWAY}${cid}`)
if (!res.ok) throw new Error(`${GATEWAY}${cid}: ${res.status}`)
const levels = ((await res.json()) as string[][]).map((l) => l.map(BigInt))
const poseidon = await buildPoseidon()
const H = (a: bigint, b: bigint): bigint => poseidon.F.toObject(poseidon([a, b]))
// LeanIMT: a node is the hash of its two children, or its only child when it has one.
let level = levels[0]
for (let i = 1; i < levels.length; i++) {
  const up: bigint[] = []
  for (let j = 0; j < level.length; j += 2) up.push(j + 1 < level.length ? H(level[j], level[j + 1]) : level[j])
  if (up.length !== levels[i].length || up.some((x, k) => x !== levels[i][k])) throw new Error(`the set's level ${i} does not hash from the one below`)
  level = up
}
if (level[0] !== root) throw new Error('the set does not hash to the root on chain')
say(`The latest root before the snapshot: \`0x${root.toString(16)}\`, published in block ${latest.blockNumber} (tx ${latest.transactionHash}), ${iso(latest.args._timestamp!)}, with CID \`${cid}\`.`)
say(`The tree at that CID has ${levels[0].length.toLocaleString('en-US')} labels in ${levels.length} levels. Every level hashes from the one below with Poseidon, and the top is the root on chain.`)

// All deposits into the ETH pool, to set the set against, and to trace one label.
const deployed = 22_153_714n // the first block with the pool's code, found by eth_getCode on 2026-10-20
const deposits = await logsOf(PP_ETH_POOL, ppDeposited, deployed, snapshot)
const labels = new Set(deposits.map((d) => d.args._label!))
const inSet = levels[0].filter((l) => labels.has(l)).length
say()
say('| | Count |')
say('|---|---|')
say(`| Labels in the association set | ${levels[0].length.toLocaleString('en-US')} |`)
say(`| Deposits into the ETH pool, blocks ${deployed} to ${snapshot} | ${deposits.length.toLocaleString('en-US')} |`)
say(`| Labels in the set that are an ETH-pool deposit | ${inSet.toLocaleString('en-US')} |`)
// Narrower: an approved ETH-pool deposit of at least T. The deposit's value is public.
const approved = new Set(levels[0])
say()
say('| T | Approved ETH-pool deposits of at least T |')
say('|---|---|')
for (const t of ['0.1', '1', '10', '100']) {
  const wei = BigInt(Number(t) * 10) * 10n ** 17n
  const n = deposits.filter((d) => approved.has(d.args._label!) && d.args._value! >= wei).length
  say(`| ${t} ETH | ${n.toLocaleString('en-US')} |`)
}
const traced = deposits.find((d) => d.args._label === levels[0][0])
say()
if (!traced) throw new Error("the set's first label is not an ETH-pool deposit")
say(`Checked by hand, the set's first label \`${levels[0][0]}\`: deposited into the ETH pool in block ${traced.blockNumber}, tx ${traced.transactionHash}, value ${formatEther(traced.args._value!)} ETH.`)

writeFileSync(new URL('./results.md', import.meta.url), `${out.join('\n')}\n`)
process.exit(0)
